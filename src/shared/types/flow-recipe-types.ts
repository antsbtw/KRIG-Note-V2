/**
 * ⭐⭐⭐ **编排档** —— 用户 2026-09-23 拍板:
 *
 * > 「下一步做一个任务编排试试,这样逐步的拆解抽象。
 * >   否则还是找不到该抽象到哪个颗粒度比较好。」
 *
 * ── 为什么现在才做 ──
 * 能力层已有 **19 个已登记的能力**(act/fetch/judge 三类),
 * `flow_run` / `flow_step_run` 两张表和 repo **早就建好了** ——
 * 但 25 处 `recordRun` **没有一处传 ctx**,于是 `flow_step_run` 恒为 **0 行**。
 * ⭐ 底座是空转的:所有能力都靠人在面板上手点,每一步孤立,
 *   出事时「哪一步坏的」只能靠人回忆。
 *
 * ── 颗粒度:一步 = 一个**已经单独验证过**的能力 ──
 *
 * ⚠️ 不拆更细(比如把采集拆成「导航/滚动/解析/入库」)。理由是实测出来的:
 * 采集内部那几件事**必须一起发生**才有意义 —— 滚动是为了触发载荷,
 * 展开是为了拿全文,补正文依赖这一趟采到的 isArticle 标记。
 * 拆开之后每一步都"成功"了,合起来却什么也没采到 ——
 * 那正是本仓反复踩的「看着成功实际没有」。
 *
 * ⚠️ 也不做更粗(比如一步就是「跑完整个 X 业务」)。
 * 粗到那个份上,`flow_step_run` 只有一行,等于没有编排。
 *
 * ⭐ 判据:**这一步失败时,人能不能一眼看出该去查什么。**
 * 四步各自有独立的失败形态(页面没到位 / 采不到数据 / 模型不答 / 没有候选),
 * 所以它们是四步。
 *
 * ── 刻意不做的事(用户 2026-04 的 Module5 设计就定过)──
 * ⚠️ **不做分支、不做循环、不做条件跳转**。
 * 编排档是「**可重组的步骤序列**」,不是一门小语言 ——
 * 一旦有了分支,「这次为什么走了那条路」又变成要人去猜的事。
 */

/** 一步用哪个能力 —— ⚠️ 与 `STEP_TYPE_OF` 的键**同一套词**,不另起名字 */
export type FlowStepKind =
  /** 导航到语义页面(act) */
  | 'goto'
  /** 采集:滚动+展开+解析+入库+补长文正文(fetch) */
  | 'collect'
  /** AI 判断哪些值得回复(judge) */
  | 'judge'
  /**
   * ⭐ 备料:给候选补齐作者 bio 与这一楼的上文(fetch)。
   * ⚠️ **先查库,缺了才去 X 取**(用户 2026-09-26 定)。
   */
  | 'prefetch'
  /**
   * ⭐ 送 Claude 取回复建议(judge)。
   * ⚠️ **只取建议**,发不发是人点的 —— 与 planReply 的红线一致。
   */
  | 'askAdvice'
  /** 拟回复草稿 —— ⚠️ **只填不发**(用户定的红线) */
  | 'planReply';

/** 编排档里的一步 */
export interface FlowStep {
  /** 步骤 id —— 在本档内唯一,失败时报的就是它 */
  id: string;
  kind: FlowStepKind;
  /** 人看的名字("采集搜索结果"),为空则用 kind */
  label?: string;
  /**
   * 这一步的参数。
   * ⚠️ **原样透传给能力**,编排层不解释它的内容 ——
   * 解释它就等于把能力的知识抄一份到编排层,两份会漂。
   */
  params?: Record<string, unknown>;
  /**
   * ⭐ 关掉这一步但**不删** —— 调试时要能只跑前两步。
   * ⚠️ 跳过的步骤照样进 `flow_step_run`(status='skipped'),
   * 否则「这次没跑」和「这次没这一步」在记录里分不开。
   */
  enabled?: boolean;
}

/**
 * 一份编排档。
 *
 * ⚠️ 存成**数据**而不是代码:用户 2026-09-23 拍板「直接做成可配置的编排档」。
 * ⭐ 所以步骤顺序、参数、开关都能改,而不用动代码 ——
 *   这正是「可重组」的意思。
 */
export interface FlowRecipe {
  recipeId: string;
  name: string;
  /**
   * ⭐⭐ **档级共享参数** —— 多个步骤都要用的东西放这里,**只写一遍**。
   *
   * ── 为什么非有不可(2026-09-24 实测的坑)──
   * 搜索词原来在档里**写了两遍**(goto 一遍、collect 一遍)。
   * 改一个忘另一个,两步就会**搜不同的词** —— 而且**不报错**:
   * 导航到 A 页、采集却去采 B 页,结果看着正常,数据却对不上。
   *
   * ⭐ 合并规则:`{ ...shared, ...step.params }` —— **步骤自己写的优先**,
   * 所以想让某一步用别的词,在那一步覆盖即可。
   *
   * ⚠️ 只放**业务参数**。运行时的东西(wcId 这种页面重开就变的)
   * 由调用方注入,不进档 —— 写进去会立刻过期。
   */
  shared?: Record<string, unknown>;
  /** 这套流程是干什么的 —— 进 flow_run.flow_name,回看时要认得出 */
  description?: string;
  steps: FlowStep[];
  /** 哪个 workspace 跑 —— ⚠️ 不填由调用方给,别在档里写死 */
  wsId?: string;
  enabled?: boolean;
  createdAt?: string;
  updatedAt?: string;
}

/**
 * ⭐ 一步跑完的结果 —— 编排层只认这三样,不认能力各自的返回形状。
 *
 * ⚠️ `ok` 与 `produced` **必须分开**:
 * 「跑成功了但一条都没产出」(如判断队列本来就空)与「跑失败了」
 * 是两回事,合在一起报会让人去查一个不存在的故障。
 */
export interface FlowStepOutcome {
  ok: boolean;
  /** 这一步产出了多少(采到几条 / 判了几条 / 拟了几条)—— 0 不等于失败 */
  produced: number;
  /** 失败原因 —— ⚠️ ok=false 时**必须**有,否则等于静默失败 */
  error?: string;
  /** 给人看的一句话,进 flow_step_run.note */
  note?: string;
  elapsedMs: number;
  /**
   * ⭐⭐ **往下传的东西** —— 下一步从这里取,不从库里捞。
   *
   * ── 为什么非有不可(2026-09-26 实测)──
   * 原来步与步之间只能传 `produced` 这**一个数**,传不了「产出的**是什么**」。
   * 而流水线的 ③④⑤ 全都要往下传东西:
   * ③ 传打包好的语境、④ 传 Claude 的建议、⑤ 传用户的选定。
   *
   * ⚠️ 用 `unknown` 不用泛型:编排层**不解释它的内容**(与 `params` 同一道理)——
   * 解释它就等于把能力的知识抄一份到编排层,两份会漂。
   */
  payload?: unknown;
  /**
   * ⭐⭐ **这一步有没有产出候选** —— `false` 时后续步骤**跳过**(不是失败)。
   *
   * ── 用户 2026-09-26 点破的 ──
   * > 「既然值得回复是零条,为什么第四步还需要跑呢?」
   *
   * ⚠️ 真因:判断步的 `produced: 10` 是「**判了** 10 条」,
   * 而真正该当闸门的「值得回复 0 条」**只写在给人看的 note 里,编排读不到**
   * —— 于是第 4 步照跑、空转 125 秒。
   *
   * ⚠️ 与 `produced === 0` **不是一回事**,别用后者代替:
   * 判断步判了 10 条(produced=10)但 worth 是 0 —— 这时才该刹车。
   * ⚠️ **留空(undefined)= 不表态**,后续照跑 —— 老能力不写它就维持原状,
   * 不会因为加了这个字段而被误刹。
   */
  hasCandidates?: boolean;
  /**
   * ⭐⭐ **观察点** —— 用户 2026-09-26:
   * > 「每一个环节都应该有观察点,这样才可以真正追溯效果。」
   *
   * ⚠️ 与 `note` 的分工:`note` 是**给人看的一句话**,
   * 这里是**给回归分析看的判据**(哪 10 条、每条什么理由)。
   * 原来 `output` 只有 `{produced, note}`,要追溯「Gemma 为什么判错」
   * 得去 `x_tweet` 反查 —— **而那张表有 TTL**,过期就查不到了。
   */
  evidence?: {
    /**
     * 关键判据。各步自定形状:
     * 判断 = 每条的 verdict + 理由 / 取数 = 命中缓存还是现取 /
     * 送 Claude = prompt 多长、回了多少字
     */
    items?: unknown[];
    /**
     * ⭐ **跨库的锚** —— 如采集 journal 的文件名。
     * ⚠️ 留痕分三处(journal 文件 / flow_step_run / x_tweet)且
     * **跨库不能 join**(SurrealDB 限制),所以存路径按名取,不指望 join。
     */
    journalRef?: string;
  };
}
